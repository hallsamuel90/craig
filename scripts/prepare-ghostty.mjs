import { createHash, randomUUID } from "node:crypto";
import { mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const GHOSTTY_VERSION = "1.0.0";
export const GHOSTTY_SHA256 = "7b428fee6d0677bc81279458f8f9a3335454834123a9ff47efb3fd177f6da5a8";
export const GHOSTTY_URL = `https://release.files.ghostty.org/libghostty-vt/${GHOSTTY_VERSION}/ghostty-vt-${GHOSTTY_VERSION}.wasm`;
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export function verifyGhostty(bytes) {
  if (createHash("sha256").update(bytes).digest("hex") !== GHOSTTY_SHA256) {
    throw new Error(`libghostty-vt ${GHOSTTY_VERSION} checksum mismatch. Refusing to embed this artifact.`);
  }
  return bytes;
}

// Build-time acquisition only. The installed CLI imports the generated literal;
// it never downloads Wasm, consults this cache, or resolves an asset path.
export async function prepareGhostty({ cacheDir = resolve(root, ".cache/libghostty"), offline = process.env.CRAIG_GHOSTTY_OFFLINE === "1" } = {}) {
  const file = resolve(cacheDir, `ghostty-vt-${GHOSTTY_VERSION}.wasm`);
  let bytes;
  try {
    bytes = verifyGhostty(await readFile(file));
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
    if (offline) throw new Error("The verified Ghostty build cache is missing. Run pnpm ghostty:prepare once with network access.");
    const response = await fetch(GHOSTTY_URL, { signal: AbortSignal.timeout(30000), redirect: "error" });
    if (!response.ok) throw new Error(`Ghostty artifact download failed: HTTP ${response.status}`);
    bytes = verifyGhostty(Buffer.from(await response.arrayBuffer()));
    await mkdir(cacheDir, { recursive: true });
    await atomicWrite(file, bytes);
  }
  const output = resolve(root, "src/ui/ghostty/wasm.generated.ts");
  const content = `// Generated by scripts/prepare-ghostty.mjs; do not edit.\nexport const GHOSTTY_VERSION = ${JSON.stringify(GHOSTTY_VERSION)};\nexport const GHOSTTY_SHA256 = ${JSON.stringify(GHOSTTY_SHA256)};\nexport const GHOSTTY_WASM_BASE64 = ${JSON.stringify(bytes.toString("base64"))};\n`;
  await mkdir(dirname(output), { recursive: true });
  const previous = await readFile(output, "utf8").catch((error) => { if (error.code !== "ENOENT") throw error; });
  if (previous !== content) await atomicWrite(output, content);
  return bytes;
}

async function atomicWrite(file, content) {
  const temporary = `${file}.${randomUUID()}.tmp`;
  try {
    await writeFile(temporary, content, { flag: "wx" });
    await rename(temporary, file);
  } finally { await rm(temporary, { force: true }); }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await prepareGhostty();
